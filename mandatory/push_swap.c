#include "push_swap.h"

int	main(int ac, char **av)
{
	t_stack	a;
	t_stack	b;

	if (ac < 2)
		return (EXIT_FAILURE);
	a = init_a(ac, av);
	b = init_b(a);
	if (!is_sorted(a))
		sort(&a, &b);
	free_all(&a, &b);
}
